/**
 * Стоит ли показывать тост о сбое запроса.
 *
 * 401 и 402 уже отрабатывает перехватчик в lib/api/client.ts — рефреш-разлогин
 * и редирект на paywall. Тост поверх них только мешает: пользователь и так
 * уезжает на другой экран.
 *
 * Всё остальное тостим. Правило намеренно «разрешительное»: незамеченный сбой
 * рисуется как пустой список и врёт, будто данных нет, — цена лишнего тоста
 * несравнимо ниже.
 */
export function shouldToastQueryError(error: unknown): boolean {
  const status = (error as { status?: unknown } | null | undefined)?.status
  return status !== 401 && status !== 402
}
