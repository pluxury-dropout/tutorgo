// Ручки пера. Крутить здесь, потом `npm run excalidraw-patch` и перезапустить dev.
//
// Физика (perfect-freehand 1.2.0, getStrokeOutlinePoints):
//
//   sp       = min(1, distance / SPEED_SCALE)   // distance = px между точками = скорость
//   pressure → 1 - sp                           // с инерцией 0.275 за точку
//   radius   = size * easing(0.5 - thinning * (0.5 - pressure))
//
// Отсюда три следствия, ради которых значения и вынесены в одно место:
//
//   1. THINNING — амплитуда. 0 отключает весь pressure-путь (радиус = size/2,
//      ровное перо, как было до возврата эффекта). 0.6 — штатное Excalidraw:
//      ширина гуляет от 0.62×size (быстро) до 1.9×size (медленно).
//   2. PEN_SCALE — толщина: ширина = strokeWidth × PEN_SCALE. Нижний конец
//      диапазона не должен уходить под 1.5px: freedraw заливается как фигура, и
//      субпиксельная ширина бледнеет в антиалиасинге. Отсюда 2.5 — при
//      strokeWidth 1 быстрый штрих даёт те же ~1.5px, что и прежнее ровное перо,
//      а медленный утолщается до ~4.7px.
//   3. SPEED_SCALE — порог скорости в px на событие указателя. В оригинале его
//      роль играет сам size, из-за чего эффект скорости зависел от толщины пера
//      и на тонком (size 1.5) насыщался в «всегда быстро»: мышь на 60 Гц легко
//      проходит 5-20px за кадр. Патч отвязывает шкалу от толщины. Больше 18 —
//      утолщение начинается на более быстрых движениях, меньше — на более
//      медленных.
//
// Всё это работает только для мыши/тачпада (simulatePressure: true). У стилуса
// Excalidraw пишет реальные element.pressures, и толщина идёт от нажима.

// @type-аннотации нужны тайпчеку: без них TS выводит литеральные типы (0.6, 18)
// и считает ветку «а если 0» в pen.test.ts недостижимой — next build падает.
/** @type {number} */ export const PEN_SCALE = 1
/** @type {number} */ export const THINNING = 0.9
/** @type {number} */ export const SPEED_SCALE = 10
